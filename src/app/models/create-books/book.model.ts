import { Schema, model } from "mongoose";
import { BookInterface } from "./book.interface";

const bookSchema = new Schema<BookInterface>({
  title: {
    type: String,
    required: true,
  },
  author: {
    type: String,
    required: true,
  },
  price: {
    type: Number,
    required: true,
  },
  category: {
    type: String,
    required: true,
  },
  description: {
    type: String,
    required: true,
  },
  quantity: {
    type: Number,
    required: true,
  },
  inStock: {
    type: Boolean,
    required: true,
  },
});

export const Book = model<BookInterface>("Book", bookSchema);
